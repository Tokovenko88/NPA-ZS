"""Модальные диалоги NPA-ZS.

Пайплайн намеренно интерактивен: там, где автоматика не может выбрать
единственно верный вариант, решение принимает оператор. Все такие точки
сосредоточены здесь.

:mod:`npazs.ui.dialogs.manual_mapping`
    ``ManualMappingDialog`` — ручное сопоставление номера изменения
    (``revision_number``) с элементом изменяющего НПА, когда автоматическое
    разрешение адреса не дало однозначного результата.

:mod:`npazs.ui.dialogs.source_mapping`
    ``SourceMappingDialog`` — выбор элемента-источника в изменяющем НПА для
    извлечения текста правки.

:mod:`npazs.ui.dialogs.extraction_conflict`
    ``ExtractionConflictDialog`` и ``resolve_extraction_conflict`` — сравнение
    двух вариантов извлечённого HTML (детерминированного программного и
    предложенного моделью) с выбором верного. Ключевой контроль качества:
    молча принять вариант модели нельзя.

:mod:`npazs.ui.dialogs.notes`
    Просмотр и правка примечаний (``item_notes`` / примечания НПА), включая
    временные интервалы действия ретроактивных оговорок.

Протокол вызова из фонового потока
----------------------------------
Диалоги создаются только в главном потоке Tk. Фоновый поток пайплайна
запрашивает диалог через ``root.after(...)`` и ждёт ответ из ``answer_queue``,
периодически проверяя ``stop_event``, чтобы отмена прогона не приводила к
зависанию на закрытом окне.
"""

