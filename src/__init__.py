"""NPA-ZS — гармонизированный конвейер обработки нормативных правовых актов.

Пакет распространяется под каноническим именем ``npazs``, но физически лежит в
каталоге ``src/``. Чтобы обе формы импорта работали одинаково — и при установке
через ``pip install -e .`` (где ``package-dir`` отображает ``npazs`` -> ``src``),
и при запуске «из исходников» — модуль регистрирует себя в ``sys.modules`` под
именем ``npazs``.

Благодаря наличию ``__path__`` у зарегистрированного модуля механизм импорта
Python корректно находит подпакеты (``npazs.core``, ``npazs.revision``, ...)
даже если корневой пакет был загружен как ``src``.

Всегда импортируйте код как ``npazs.*``. Смешивание ``src.*`` и ``npazs.*``
в одном процессе приведёт к двойной загрузке модулей и к рассинхронизации
monkey-patch-хуков из ``npazs.revision.__init__``.
"""

import sys

__version__ = "1.0.0"
__all__ = ["__version__"]

# Канонический алиас: делает `import npazs.<sub>` рабочим даже когда этот
# каталог был импортирован под другим именем (например, как `src`).
if __name__ != "npazs":  # pragma: no cover - зависит от способа запуска
    sys.modules.setdefault("npazs", sys.modules[__name__])
